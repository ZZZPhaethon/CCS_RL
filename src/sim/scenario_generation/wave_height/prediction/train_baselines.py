from __future__ import annotations

import argparse
from pathlib import Path

from .baselines import evaluate_persistence, evaluate_seasonal_climatology, record_summary
from .dataset import DEFAULT_TARGET_COLUMN, WaveRouteDataset


def evaluate_wave_height_baselines(
    csv_path: str | Path,
    *,
    lookback_hours: int = 72,
    horizon_hours: int = 24,
    target_column: str = DEFAULT_TARGET_COLUMN,
) -> dict[str, dict[str, float | int]]:
    dataset = WaveRouteDataset.from_csv(csv_path)
    splits = dataset.split_by_years(
        train_years=(2010, 2011, 2012),
        validation_years=(2013,),
        test_years=(2014,),
    )
    validation_samples = splits["validation"].make_samples(
        lookback_hours=lookback_hours,
        horizon_hours=horizon_hours,
        target_column=target_column,
    )
    test_samples = splits["test"].make_samples(
        lookback_hours=lookback_hours,
        horizon_hours=horizon_hours,
        target_column=target_column,
    )

    return {
        "train_summary": record_summary(splits["train"].records, target_column=target_column),
        "validation_persistence": evaluate_persistence(validation_samples).as_dict(),
        "validation_seasonal": evaluate_seasonal_climatology(
            splits["train"],
            validation_samples,
            target_column=target_column,
        ).as_dict(),
        "test_persistence": evaluate_persistence(test_samples).as_dict(),
        "test_seasonal": evaluate_seasonal_climatology(
            splits["train"],
            test_samples,
            target_column=target_column,
        ).as_dict(),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Evaluate route-level wave-height forecast baselines.")
    parser.add_argument(
        "--csv",
        type=Path,
        default=Path("output/wave_height/phase1_route_wave_2010_2014.csv"),
        help="Route-level wave-height CSV generated by preprocessing.py.",
    )
    parser.add_argument("--lookback-hours", type=int, default=72)
    parser.add_argument("--horizon-hours", type=int, default=24)
    parser.add_argument("--target-column", default=DEFAULT_TARGET_COLUMN)
    args = parser.parse_args()

    results = evaluate_wave_height_baselines(
        args.csv,
        lookback_hours=args.lookback_hours,
        horizon_hours=args.horizon_hours,
        target_column=args.target_column,
    )
    for name, metrics in results.items():
        print(name)
        for key, value in metrics.items():
            print(f"  {key}: {value}")


if __name__ == "__main__":
    main()
